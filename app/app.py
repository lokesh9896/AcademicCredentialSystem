def generate_certificate_pdf(
    student_name: str,
    student_id: str,
    degree: str,
    institution: str,
    credential_id: str,
) -> bytes:
    """Generate a sample academic certificate PDF in memory."""

    buffer = io.BytesIO()
    width, height = landscape(A4)
    pdf = canvas.Canvas(buffer, pagesize=(width, height))

    pdf.setTitle(f"Academic Certificate - {credential_id}")

    # Certificate borders
    pdf.setStrokeColorRGB(0.12, 0.25, 0.45)
    pdf.setLineWidth(4)
    pdf.rect(25, 25, width - 50, height - 50)

    pdf.setLineWidth(1)
    pdf.rect(35, 35, width - 70, height - 70)

    # Certificate heading
    pdf.setFillColorRGB(0.12, 0.25, 0.45)
    pdf.setFont("Helvetica-Bold", 24)
    pdf.drawCentredString(
        width / 2, height - 100, institution.upper()
    )

    pdf.setFillColorRGB(0, 0, 0)
    pdf.setFont("Helvetica-Bold", 20)
    pdf.drawCentredString(
        width / 2, height - 145, "ACADEMIC CERTIFICATE"
    )

    pdf.setFont("Helvetica", 14)
    pdf.drawCentredString(
        width / 2, height - 185, "This certificate is issued to"
    )

    pdf.setFont("Helvetica-Bold", 23)
    pdf.drawCentredString(
        width / 2, height - 225, student_name
    )

    pdf.setFont("Helvetica", 14)
    pdf.drawCentredString(
        width / 2, height - 265, f"Student ID: {student_id}"
    )
    pdf.drawCentredString(
        width / 2, height - 295, f"Degree: {degree}"
    )
    pdf.drawCentredString(
        width / 2, height - 325, f"Institution: {institution}"
    )
    pdf.drawCentredString(
        width / 2, height - 355, f"Credential ID: {credential_id}"
    )

    pdf.setFont("Helvetica-Oblique", 9)
    pdf.drawCentredString(
        width / 2,
        55,
        "Generated by the Academic Credential Verification System",
    )

    pdf.save()
    buffer.seek(0)
    return buffer.getvalue()


